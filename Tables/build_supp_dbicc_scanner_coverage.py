#!/usr/bin/env python3
"""Compare full-vector dbICC in the full sample and four shared scanners."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from Analyses import figure2_reliability as analysis
from tools.prepare_reproduction_selections import validate_acquisitions

SHARED_SCANNERS = frozenset({"NOT1ACH", "NOT2ING", "OXF1PRI", "OXF2PRI"})
STEM = "supp_table_dbicc_scanner_coverage"


def coverage_metrics(frame: pd.DataFrame, features: list[str], samples: np.ndarray) -> dict:
    full = analysis.select_primary_acquisition_per_cell(frame)
    shared = full.loc[full["scanner"].isin(SHARED_SCANNERS)].copy()
    for name, cells, count, scanners in (("full", full, 6, 8), ("shared", shared, 4, 4)):
        if (len(cells) != 20 * count or cells["subject_id"].nunique() != 20
                or cells["scanner"].nunique() != scanners
                or not cells.groupby("subject_id").size().eq(count).all()):
            raise ValueError(f"Wrong {name} acquisition design")
    if sorted(full["subject_id"].unique()) != sorted(shared["subject_id"].unique()):
        raise ValueError("Participant sets differ between full and restricted samples")
    return {"full": analysis.compute_dbicc(full, features, samples),
            "shared": analysis.compute_dbicc(shared, features, samples)}


def render_table(summary: pd.DataFrame) -> str:
    lines = [
        "% Generated by build_supp_dbicc_scanner_coverage.py; do not edit values manually.",
        r"\begin{tabular}{lcc}", r"\toprule",
        r"Representation & \shortstack{Full sample\\120 acquisitions} & \shortstack{Shared scanners\\80 acquisitions} \\",
        r"\midrule",
    ]
    for row in summary.to_dict(orient="records"):
        entries = [row["model"]]
        for mode in ("full", "shared"):
            entries.append(f"{row[f'{mode}_estimate']:.2f} [{row[f'{mode}_ci_lower']:.2f}, {row[f'{mode}_ci_upper']:.2f}]")
        lines.append(" & ".join(entries) + r" \\")
    return "\n".join([*lines, r"\bottomrule", r"\end{tabular}", ""])


def build(args) -> pd.DataFrame:
    data_root = args.data_root.expanduser().resolve()
    output = args.output_dir.expanduser().resolve()
    if args.n_bootstrap < 1:
        raise ValueError("Bootstrap count must be positive")
    selections_path = data_root / "selections.json"
    acquisitions_path = data_root / "ON-Harmony/acquisitions.csv"
    selection_manifest = json.loads(selections_path.read_text())
    if analysis.sha256_file(acquisitions_path) != selection_manifest["files"]["ON-Harmony/acquisitions.csv"]["sha256"]:
        raise ValueError("Acquisition selection checksum mismatch")
    acquisitions = pd.read_csv(acquisitions_path, dtype=str)
    validate_acquisitions(acquisitions.to_dict(orient="records"))
    reference_keys = analysis.canonical_keys(acquisitions.rename(columns={"participant_id": "subject_id"}))
    inventory_path = data_root / "ON-Harmony/inventory.csv"
    inventory = pd.read_csv(inventory_path, keep_default_na=False)
    specs = [spec for spec in analysis.INPUT_SPECS if spec.condition != "freesurfer_combat"]
    paths = [data_root / "ON-Harmony/embeddings" / f"{spec.condition}.csv" for spec in specs]
    sources = [*paths, acquisitions_path, selections_path, inventory_path,
               Path(__file__).resolve(), Path(analysis.__file__)]
    reference = None
    if args.reference_results is not None:
        reference = json.loads(args.reference_results.read_text())
        sources.append(args.reference_results.resolve())
    hashes = {str(path): analysis.sha256_file(path) for path in sources}
    samples = analysis.bootstrap_indices(20, args.n_bootstrap, args.seed)
    rows, fold_rows, conditions = [], [], {}
    for spec, path in zip(specs, paths):
        expected_hashes = set(inventory.loc[inventory["file"].eq(f"embeddings/{path.name}"), "csv_sha256"])
        if expected_hashes != {hashes[str(path)]}:
            raise ValueError(f"Published embedding checksum mismatch: {path}")
        frame = pd.read_csv(path, float_precision="round_trip", keep_default_na=False).rename(
            columns={"participant_id": "subject_id"})
        features = analysis.numbered_columns(frame, "emb_")
        if len(features) != spec.expected_dimensions:
            raise ValueError(f"Wrong embedding dimension: {path}")
        if not np.isfinite(frame[features].to_numpy(dtype=float)).all():
            raise ValueError(f"Nonfinite embedding values: {path}")
        variants = [f"fold{i}" for i in range(5)] if len(spec.files) == 5 else ["canonical"]
        if set(frame["variant"]) != set(variants):
            raise ValueError(f"Unexpected variants: {path}")
        fold_results = []
        for variant in variants:
            group = frame.loc[frame["variant"].eq(variant)]
            if len(group) != 165 or not analysis.canonical_keys(group).equals(reference_keys):
                raise ValueError(f"Acquisition identities differ: {path}/{variant}")
            metrics = coverage_metrics(group, features, samples)
            fold_results.append(metrics)
            for mode, result in metrics.items():
                fold_rows.append({"condition": spec.condition, "variant": variant, "sample": mode,
                                  **{key: result[key] for key in ("estimate", "ci_lower", "ci_upper")}})
        combined = {mode: analysis.aggregate_fold_results([fold_results[i][mode] for i in spec.primary_folds])
                    for mode in ("full", "shared")}
        if reference is not None:
            expected = reference["conditions"][spec.condition]["dbicc"]
            for key in ("estimate", "ci_lower", "ci_upper", "bootstrap_values"):
                np.testing.assert_allclose(combined["full"][key], expected[key], rtol=0, atol=1e-10,
                                           err_msg=f"Cannot reproduce primary result: {spec.condition}/{key}")
        row = {"condition": spec.condition,
               "model": "AnatCL--SimCLR" if spec.condition == "matched_simclr" else spec.label}
        for mode, result in combined.items():
            row.update({f"{mode}_{key}": result[key] for key in ("estimate", "ci_lower", "ci_upper")})
        rows.append(row)
        conditions[spec.condition] = {"aggregate": combined, "primary_folds": list(spec.primary_folds), "folds": fold_results}
    if any(analysis.sha256_file(Path(path)) != checksum for path, checksum in hashes.items()):
        raise ValueError("An input or statistical source file changed during calculation")
    summary = pd.DataFrame(rows)
    output.mkdir(parents=True, exist_ok=True)
    analysis.atomic_csv(output / f"{STEM}.csv", summary)
    analysis.atomic_csv(output / f"{STEM}_folds.csv", pd.DataFrame(fold_rows))
    tex_path = output / f"{STEM}.tex"
    tex_path.write_text(render_table(summary), encoding="utf-8")
    analysis.atomic_json(output / f"{STEM}.manifest.json", {
        "status": "PASS", "created_utc": datetime.now(timezone.utc).isoformat(),
        "analysis": "Post hoc sensitivity of full-vector dbICC to scanner coverage",
        "primary_analysis_unchanged": True,
        "full_sample": {"participants": 20, "acquisitions": 120, "scanners": 8, "scanners_per_participant": 6},
        "restricted_sample": {"participants": 20, "acquisitions": 80, "scanners": sorted(SHARED_SCANNERS),
                              "scanners_per_participant": 4},
        "bootstrap": {"n": args.n_bootstrap, "seed": args.seed,
                      "method": "same unstratified participant resamples for both samples and all folds",
                      "samples_sha256": hashlib.sha256(samples.astype(np.int64).tobytes()).hexdigest(),
                      "duplicate_correction": "copies of the same participant excluded from between-participant pairs"},
        "fold_aggregation": "selected primary checkpoint; all fold estimates retained separately; embeddings are not averaged",
        "sources_and_code_sha256": hashes,
        "primary_reference_checked": args.reference_results is not None,
        "conditions": conditions,
        "outputs": {path.name: analysis.sha256_file(path) for path in (
            tex_path, output / f"{STEM}.csv", output / f"{STEM}_folds.csv")},
    })
    return summary


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path, default=ROOT / "data")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--reference-results", type=Path, help="Optional primary-analysis JSON to verify the full-sample results")
    parser.add_argument("--n-bootstrap", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    print(build(parser.parse_args()).to_string(index=False))
