#!/usr/bin/env python3
"""Compare native and coordinate-standardised dbICC without changing Figure 2.

Run with the local conda base Python. Inputs are the hash-bound Figure 2
tables; only the first acquisition in each participant-scanner cell is used.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys

import numpy as np
import pandas as pd
from sklearn.preprocessing import StandardScaler

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from Analyses.figure2_reliability import (  # noqa: E402
    INPUT_SPECS,
    METADATA_COLUMNS,
    atomic_csv,
    atomic_json,
    canonical_keys,
    distance_blocks,
    numbered_columns,
    point_dbicc,
    select_primary_acquisition_per_cell,
    sha256_file,
)

SPECS = tuple(spec for spec in INPUT_SPECS if spec.condition != "freesurfer_combat")


def scaling_scores(frame: pd.DataFrame, features: list[str]) -> dict:
    cells = select_primary_acquisition_per_cell(frame)
    values = cells[features].to_numpy(dtype=np.float64)
    if not features or not np.isfinite(values).all():
        raise ValueError("Features must be present and finite")
    native = point_dbicc(distance_blocks(cells, features))[0]
    scaled = cells.copy()
    scaler = StandardScaler()
    scaled[features] = scaler.fit_transform(values)
    standardised = point_dbicc(distance_blocks(scaled, features))[0]
    return {
        "native_dbicc": native,
        "standardised_dbicc": standardised,
        "constant_dimensions": int(np.count_nonzero(scaler.var_ == 0)),
    }


def load_bound_input(path: Path, expected_sha: str, dimensions: int) -> pd.DataFrame:
    if sha256_file(path) != expected_sha:
        raise ValueError(f"Figure 2 input SHA mismatch: {path}")
    frame = pd.read_csv(path)
    features = numbered_columns(frame, "emb_")
    if len(frame) != 165 or len(features) != dimensions:
        raise ValueError(f"Unexpected input size: {path}")
    if frame[list(METADATA_COLUMNS)].isna().any().any():
        raise ValueError(f"Missing acquisition metadata: {path}")
    if frame.duplicated(list(METADATA_COLUMNS)).any():
        raise ValueError(f"Duplicate acquisition: {path}")
    selected = select_primary_acquisition_per_cell(frame)
    if (
        len(selected) != 120
        or selected["subject_id"].nunique() != 20
        or selected["scanner"].nunique() != 8
        or not selected.groupby("subject_id").size().eq(6).all()
        or not selected["session_id"].astype(str).str.endswith("001").all()
    ):
        raise ValueError(f"Unexpected primary cohort: {path}")
    if sha256_file(path) != expected_sha:
        raise ValueError(f"Input changed during loading: {path}")
    return frame


def summarise(folds: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for condition, group in folds.groupby("condition", sort=False):
        row = {
            "condition": condition,
            "model": group["model"].iloc[0],
            "dimensions": int(group["dimensions"].iloc[0]),
            "folds": len(group),
        }
        for mode in ("native", "standardised"):
            values = group[f"{mode}_dbicc"]
            row[f"{mode}_dbicc"] = float(values.mean())
            row[f"{mode}_fold_sd"] = float(values.std(ddof=1)) if len(group) > 1 else 0.0
        rows.append(row)
    result = pd.DataFrame(rows)
    for mode in ("native", "standardised"):
        result[f"{mode}_rank"] = result[f"{mode}_dbicc"].rank(
            ascending=False, method="min"
        ).astype(int)
    return result.sort_values("native_rank", kind="stable").reset_index(drop=True)


def render_table(summary: pd.DataFrame) -> str:
    lines = [
        "% Generated by build_supp_dbicc_scaling.py; do not edit values manually.",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r" & & \multicolumn{2}{c}{Native features} & \multicolumn{2}{c}{Standardised features} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
        r"Representation & Dimensions & dbICC & Rank & dbICC & Rank \\",
        r"\midrule",
    ]
    for row in summary.itertuples():
        lines.append(
            f"{row.model} & {row.dimensions} & {row.native_dbicc:.3f} & "
            f"{row.native_rank} & {row.standardised_dbicc:.3f} & "
            f"{row.standardised_rank} " + r"\\"
        )
    return "\n".join([*lines, r"\bottomrule", r"\end{tabular}", ""])


def build(input_root: Path, results_path: Path, output_dir: Path) -> pd.DataFrame:
    results_sha = sha256_file(results_path)
    results = json.loads(results_path.read_text())
    rows, sources = [], []
    reference_keys = None
    for spec in SPECS:
        condition = results["conditions"][spec.condition]
        inputs = condition["inputs"]
        if len(inputs) != len(spec.files):
            raise ValueError(f"Missing or extra folds for {spec.condition}")
        for fold, record in enumerate(inputs):
            filename = f"{spec.condition}__fold{fold}.csv"
            if Path(record["analysis_input"]).name != filename:
                raise ValueError(f"Unexpected fold identity: {record['analysis_input']}")
            path = input_root / filename
            frame = load_bound_input(path, record["analysis_input_sha256"], spec.expected_dimensions)
            keys = canonical_keys(frame)
            if reference_keys is None:
                reference_keys = keys
            elif not keys.equals(reference_keys):
                raise ValueError(f"Acquisition order/set mismatch: {filename}")
            scores = scaling_scores(frame, numbered_columns(frame, "emb_"))
            expected = condition["fold_dbicc"][fold]["estimate"]
            if not np.isclose(scores["native_dbicc"], expected, rtol=0, atol=1e-10):
                raise ValueError(f"Cannot reproduce Figure 2 dbICC: {filename}")
            rows.append({
                "condition": spec.condition,
                "model": "AnatCL--SimCLR" if spec.condition == "matched_simclr" else spec.label,
                "fold": fold,
                "dimensions": spec.expected_dimensions,
                **scores,
            })
            sources.append({"path": str(path.resolve()), "sha256": record["analysis_input_sha256"]})
    folds = pd.DataFrame(rows)
    summary = summarise(folds)
    for row in summary.itertuples():
        expected = results["conditions"][row.condition]["dbicc"]["estimate"]
        if not np.isclose(row.native_dbicc, expected, rtol=0, atol=1e-10):
            raise ValueError(f"Fold aggregation differs from Figure 2: {row.condition}")
    for source in sources:
        if sha256_file(Path(source["path"])) != source["sha256"]:
            raise ValueError(f"Source changed: {source['path']}")
    if sha256_file(results_path) != results_sha:
        raise ValueError("Figure 2 results changed during analysis")
    output_dir.mkdir(parents=True, exist_ok=True)
    atomic_csv(output_dir / "supp_table_dbicc_scaling.csv", summary)
    atomic_csv(output_dir / "supp_table_dbicc_scaling_folds.csv", folds)
    tex_path = output_dir / "supp_table_dbicc_scaling.tex"
    tex_path.write_text(render_table(summary))
    atomic_json(output_dir / "supp_table_dbicc_scaling.manifest.json", {
        "status": "PASS",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "analysis": "Post hoc sensitivity to coordinate scaling; point-estimate rankings only",
        "primary_unchanged": True,
        "cohort": {"participants": 20, "acquisitions": 120, "scanners": 8, "selection": "first acquisition per cell"},
        "standardisation": "StandardScaler fitted separately per representation/fold on the 120 selected acquisitions; population SD; constant features set to zero",
        "aggregation": "Mean of five independently calculated fold dbICCs for AnatCL and AnatCL-SimCLR; one run for others; no embedding averaging",
        "rank": "Descending point estimate across nine representations; exact ties share the minimum rank",
        "figure2_results": {"path": str(results_path.resolve()), "sha256": results_sha},
        "inputs": sources,
        "code": {str(Path(__file__).resolve()): sha256_file(Path(__file__)),
                 "Analyses/figure2_reliability.py": sha256_file(PROJECT_ROOT / "Analyses/figure2_reliability.py")},
        "table_sha256": sha256_file(tex_path),
    })
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-root", type=Path, default=PROJECT_ROOT / "Results/Figure2/inputs")
    parser.add_argument("--figure2-results", type=Path, default=PROJECT_ROOT / "Results/Figure2/figure2_reliability_results.json")
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    print(build(args.input_root, args.figure2_results, args.output_dir).to_string(index=False))


if __name__ == "__main__":
    main()
